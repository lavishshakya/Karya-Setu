/** Rule-based matcher used by the eligibility checker (and Setu AI). */
export function eligibleSchemes(person) {
  return schemes.filter(({ rules }) => {
    if (rules.minAge && person.age < rules.minAge) return false
    if (rules.maxAge && person.age > rules.maxAge) return false
    if (rules.maxIncome && person.income > rules.maxIncome) return false
    if (rules.skills && !rules.skills.includes(person.skill)) return false
    return true
  })
}
