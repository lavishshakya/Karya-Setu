// One-page payslip PDF (jsPDF, lazy-loaded). Amounts use "Rs." because the
// built-in PDF fonts have no ₹ glyph.
const rs = (n) => `Rs. ${new Intl.NumberFormat('en-IN').format(n)}`

export async function downloadPayslip(payment, workerName) {
  const { jsPDF } = await import('jspdf')
  const doc = new jsPDF({ unit: 'pt', format: 'a5' })
  const W = doc.internal.pageSize.getWidth()

  doc.setFillColor(11, 122, 148)
  doc.rect(0, 0, W, 78, 'F')
  doc.setTextColor(255, 255, 255)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(18)
  doc.text('Karya Setu · Payslip', 28, 38)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  doc.text(`${payment.id} · ${payment.period}`, 28, 58)

  const rows = [
    ['Worker', workerName],
    ['Employer', payment.employer],
    ['Days worked', String(payment.days)],
    ['Daily rate', rs(payment.rate)],
    ['Gross wages', rs(payment.gross)],
    ['Deductions / advance', rs(payment.deductions)],
    ['Net paid', rs(payment.net)],
    ['Status', payment.status.toUpperCase()],
    ['Method', payment.method],
  ]
  let y = 112
  doc.setTextColor(15, 26, 42)
  rows.forEach(([label, value], i) => {
    if (i % 2 === 0) {
      doc.setFillColor(241, 244, 248)
      doc.rect(20, y - 15, W - 40, 24, 'F')
    }
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(10)
    doc.text(label, 28, y)
    doc.setFont('helvetica', label === 'Net paid' ? 'bold' : 'normal')
    doc.text(value, W - 28, y, { align: 'right' })
    y += 24
  })

  doc.setFontSize(8.5)
  doc.setTextColor(102, 112, 133)
  doc.text('Generated by Karya Setu. Raise any dispute from the Complaints page within 30 days.', 28, y + 24, {
    maxWidth: W - 56,
  })
  doc.save(`${payment.id}.pdf`)
}
